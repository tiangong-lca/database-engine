CREATE TABLE IF NOT EXISTS "util"."dataset_derivative_rebuild_requests" (
    "id" "uuid" DEFAULT "gen_random_uuid"() NOT NULL,
    "actor_user_id" "uuid" NOT NULL,
    "plan_sha256" "text" NOT NULL,
    "operation_id" "text" NOT NULL,
    "action_id" "text" NOT NULL,
    "target_table" "text" DEFAULT 'processes'::"text" NOT NULL,
    "target_id" "uuid" NOT NULL,
    "target_version" "text" NOT NULL,
    "target_visibility" "text" DEFAULT 'owner_draft'::"text" NOT NULL,
    "expected_snapshot_sha256" "text" NOT NULL,
    "expected_modified_at" timestamp with time zone NOT NULL,
    "expected_json_sha256" "text" NOT NULL,
    "expected_json_ordered_sha256" "text" NOT NULL,
    "before_extracted_md_sha256" "text",
    "before_embedding_ft_sha256" "text",
    "before_embedding_ft_at" timestamp with time zone,
    "plan_request_sha256" "text" NOT NULL,
    "action_request_sha256" "text" NOT NULL,
    "reason_code" "text" NOT NULL,
    "status" "text" DEFAULT 'queued'::"text" NOT NULL,
    "phase" "text" DEFAULT 'admitted'::"text" NOT NULL,
    "admitted_at" timestamp with time zone DEFAULT "clock_timestamp"() NOT NULL,
    "drain_not_before" timestamp with time zone NOT NULL,
    "markdown_request_id" bigint,
    "markdown_dispatched_at" timestamp with time zone,
    "markdown_deadline_at" timestamp with time zone,
    "markdown_response_status" integer,
    "markdown_response_received_at" timestamp with time zone,
    "markdown_proposal_id" bigint,
    "accepted_extracted_md_sha256" "text",
    "embedding_pending_job_id" bigint,
    "embedding_queue_msg_id" bigint,
    "embedding_queued_at" timestamp with time zone,
    "embedding_deadline_at" timestamp with time zone,
    "embedding_proposal_id" bigint,
    "completed_snapshot_sha256" "text",
    "completed_at" timestamp with time zone,
    "terminal_at" timestamp with time zone,
    "drained_at" timestamp with time zone,
    "failure_release_not_before" timestamp with time zone,
    "last_error" "jsonb",
    "action_audit_id" bigint NOT NULL,
    "summary_audit_id" bigint NOT NULL,
    "quarantined_http_requests" integer DEFAULT 0 NOT NULL,
    "quarantined_embedding_jobs" integer DEFAULT 0 NOT NULL,
    "quarantined_pending_jobs" integer DEFAULT 0 NOT NULL,
    "created_at" timestamp with time zone DEFAULT "clock_timestamp"() NOT NULL,
    "updated_at" timestamp with time zone DEFAULT "clock_timestamp"() NOT NULL,
    "batch_id" "uuid",
    "batch_ordinal" smallint,
    "batch_target_count" smallint,
    "source_baseline_snapshot_sha256" "text",
    CONSTRAINT "dataset_derivative_rebuild_request_batch_check" CHECK (((("batch_id" IS NULL) AND ("batch_ordinal" IS NULL) AND ("batch_target_count" IS NULL) AND ("source_baseline_snapshot_sha256" IS NULL)) OR (("batch_id" IS NOT NULL) AND (("batch_ordinal" >= 1) AND ("batch_ordinal" <= 50)) AND (("batch_target_count" >= 1) AND ("batch_target_count" <= 50)) AND ("batch_ordinal" <= "batch_target_count") AND ("source_baseline_snapshot_sha256" ~ '^[a-f0-9]{64}$'::"text")))),
    CONSTRAINT "dataset_derivative_rebuild_request_counts_check" CHECK ((("quarantined_http_requests" >= 0) AND ("quarantined_embedding_jobs" >= 0) AND ("quarantined_pending_jobs" >= 0))),
    CONSTRAINT "dataset_derivative_rebuild_request_hashes_check" CHECK ((("plan_sha256" ~ '^[a-f0-9]{64}$'::"text") AND ("expected_snapshot_sha256" ~ '^[a-f0-9]{64}$'::"text") AND ("expected_json_sha256" ~ '^[a-f0-9]{64}$'::"text") AND ("expected_json_ordered_sha256" ~ '^[a-f0-9]{64}$'::"text") AND ("plan_request_sha256" ~ '^[a-f0-9]{64}$'::"text") AND ("action_request_sha256" ~ '^[a-f0-9]{64}$'::"text") AND (("before_extracted_md_sha256" IS NULL) OR ("before_extracted_md_sha256" ~ '^[a-f0-9]{64}$'::"text")) AND (("before_embedding_ft_sha256" IS NULL) OR ("before_embedding_ft_sha256" ~ '^[a-f0-9]{64}$'::"text")))),
    CONSTRAINT "dataset_derivative_rebuild_request_status_check" CHECK (("status" = ANY (ARRAY['queued'::"text", 'dispatching'::"text", 'markdown_pending'::"text", 'embedding_pending'::"text", 'completed'::"text", 'stale'::"text", 'failed'::"text"]))),
    CONSTRAINT "dataset_derivative_rebuild_request_table_check" CHECK (("target_table" = ANY (ARRAY['flows'::"text", 'processes'::"text"]))),
    CONSTRAINT "dataset_derivative_rebuild_request_terminal_check" CHECK (((("status" = ANY (ARRAY['completed'::"text", 'stale'::"text", 'failed'::"text"])) AND ("terminal_at" IS NOT NULL)) OR (("status" <> ALL (ARRAY['completed'::"text", 'stale'::"text", 'failed'::"text"])) AND ("terminal_at" IS NULL)))),
    CONSTRAINT "dataset_derivative_rebuild_request_visibility_check" CHECK (("target_visibility" = 'owner_draft'::"text"))
);

ALTER TABLE "util"."dataset_derivative_rebuild_requests" OWNER TO "postgres";

COMMENT ON TABLE "util"."dataset_derivative_rebuild_requests" IS 'Private durable coordinator state for owner-draft flow/process derivative rebuilds. Nonterminal rows are target write fences; batch_id binds protected alias child sets.';

